"""
speakup/services/feedback_schemas.py
──────────────────────────────────────
Dataclasses for the AI Feedback Engine.

No Qt, no DB, no model dependencies — safe to import anywhere.

Design note
───────────
AIFeedbackResult carries a ``source`` field that explicitly distinguishes
between objective measured metrics and AI-generated observations.  The UI
must display this distinction clearly so users understand the provenance of
each piece of feedback.

  source = "local"  — derived deterministically from the transcript text
                       using regex/heuristics (no external API, no inference)
  source = "llm"    — generated by an LLM via the OpenAI API

Neither source should fabricate errors that are not evidenced in the transcript.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional


# ---------------------------------------------------------------------------
# Input
# ---------------------------------------------------------------------------

@dataclass
class FeedbackRequest:
    """
    Everything the feedback engine needs to analyse a session.

    All fields are optional so the caller can provide as much or as little
    context as is available.
    """

    transcript:      str = ""
    topic:           str = ""
    category:        str = ""
    duration_seconds: int = 0
    words_per_minute: float = 0.0
    filler_word_count: int = 0
    filler_counts:   dict[str, int] = field(default_factory=dict)
    fluency_score:   float = 0.0
    vocabulary_score: float = 0.0
    grammar_score:   float = 0.0
    confidence_score: float = 0.0
    overall_score:   float = 0.0
    repeated_words:  dict[str, int] = field(default_factory=dict)

    # Optional prior-session averages for personalised advice
    prior_avg_overall:    Optional[float] = None
    prior_avg_confidence: Optional[float] = None


# ---------------------------------------------------------------------------
# Output
# ---------------------------------------------------------------------------

@dataclass
class GrammarCorrection:
    """
    A single grammar observation.

    Only populated when there is clear textual evidence — never fabricated.
    """
    original:    str       # The problematic phrase as it appears in the transcript
    suggestion:  str       # The recommended correction
    explanation: str       # Why this is an issue


@dataclass
class VocabularySuggestion:
    """A word the speaker used repeatedly, with richer alternatives."""
    word:         str
    count:        int           # How many times it appeared
    alternatives: list[str]


@dataclass
class AIFeedbackResult:
    """
    Complete AI-generated feedback for one practice session.

    The ``source`` field MUST be displayed in the UI so users know
    whether feedback is from rule-based local analysis or an LLM.

    Fields labelled 'objective' contain only data derived directly from
    the transcript without inference.  Fields labelled 'ai_generated'
    require LLM inference.
    """

    # Provenance — MUST be surfaced in the UI
    source: str = "local"    # "local" | "llm"
    model:  str = ""         # e.g. "gpt-4o-mini", "local/rule-based"

    # ── Objective / locally derived ──────────────────────────────────────
    grammar_corrections: list[GrammarCorrection] = field(default_factory=list)
    vocabulary_suggestions: list[VocabularySuggestion] = field(default_factory=list)
    filler_reduction_tips: list[str] = field(default_factory=list)
    repeated_word_tips:    list[str] = field(default_factory=list)

    # ── AI-generated (LLM only) ───────────────────────────────────────────
    better_sentence_alternatives: list[str] = field(default_factory=list)
    topic_specific_feedback:      list[str] = field(default_factory=list)
    personalized_practice_advice: list[str] = field(default_factory=list)

    # Status
    error:   Optional[str] = None   # set on failure
    warning: Optional[str] = None   # set when fallback was used

    @property
    def has_content(self) -> bool:
        """Return True when at least one feedback item exists."""
        return any([
            self.grammar_corrections,
            self.vocabulary_suggestions,
            self.filler_reduction_tips,
            self.repeated_word_tips,
            self.better_sentence_alternatives,
            self.topic_specific_feedback,
            self.personalized_practice_advice,
        ])

    @property
    def is_llm(self) -> bool:
        return self.source == "llm"

    @property
    def source_label(self) -> str:
        """Human-readable label shown in the UI badge."""
        if self.source == "llm":
            return f"AI-Generated  ·  {self.model}"
        return "Local Analysis  ·  Rule-Based"

    @classmethod
    def empty(cls, error: str = "", source: str = "local") -> "AIFeedbackResult":
        return cls(source=source, error=error or None)
